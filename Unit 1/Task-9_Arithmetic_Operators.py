# Read two numbers
a = float(input("Enter the first number: "))
b = float(input("Enter the second number: "))

# Perform arithmetic operations
print("Addition (+) =", a + b)
print("Subtraction (-) =", a - b)
print("Multiplication (*) =", a * b)
print("Division (/) =", a / b)
print("Floor Division (//) =", a // b)
print("Modulus (%) =", a % b)
print("Exponentiation (**) =", a ** b)
