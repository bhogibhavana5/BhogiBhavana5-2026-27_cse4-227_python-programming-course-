# Demonstrate operator precedence
result1 = 10 + 5 * 2
print("10 + 5 * 2 =", result1)

result2 = (10 + 5) * 2
print("(10 + 5) * 2 =", result2)

# Demonstrate left-to-right associativity
result3 = 20 - 5 - 3
print("20 - 5 - 3 =", result3)

# Demonstrate right-to-left associativity
result4 = 2 ** 3 ** 2
print("2 ** 3 ** 2 =", result4)
