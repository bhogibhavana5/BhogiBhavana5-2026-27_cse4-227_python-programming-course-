
# Create a tuple
fruits = ("Apple", "Banana", "Mango", "Orange")

# Display the tuple
print("Tuple:", fruits)

# Access elements using indexing
print("First element:", fruits[0])
print("Second element:", fruits[1])
print("Last element:", fruits[-1])

# Traverse the tuple
print("Tuple elements:")
for fruit in fruits:
    print(fruit)

